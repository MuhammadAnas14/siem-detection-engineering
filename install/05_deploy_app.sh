#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# Deploys the siem_core app onto the Splunk Enterprise instance: copies the
# content, substitutes site-specific values from splunk.env, validates the
# configuration with btool, and restarts.
#
# local/ is preserved across deploys, so rule tuning done through the UI
# survives a content update.
#
#   sudo ./05_deploy_app.sh
# ---------------------------------------------------------------------------
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/00_common.sh"
require_root

APP_SRC="${REPO_DIR}/apps/siem_core"
APP_DST="${SPLUNK_HOME}/etc/apps/siem_core"

[[ -d "${APP_SRC}" ]] || die "app source not found: ${APP_SRC}"
[[ -d "${SPLUNK_HOME}" ]] || die "SPLUNK_HOME not found: ${SPLUNK_HOME}"

# --- copy the app ----------------------------------------------------------
log "deploying siem_core -> ${APP_DST}"
# local/ is preserved: it holds any UI-side tuning the analysts have done.
mkdir -p "${APP_DST}"
rsync -a --delete --exclude 'local/' --exclude 'local.meta' \
    "${APP_SRC}/" "${APP_DST}/"
mkdir -p "${APP_DST}/local" "${APP_DST}/metadata"

# --- environment substitution ----------------------------------------------
# default/ ships with placeholder addresses; re-point them at whatever
# splunk.env declares so the same content deploys to any environment.
log "substituting environment values"
find "${APP_DST}/default" -name '*.conf' -print0 | xargs -0 sed -i \
    -e "s|soc@example\.com|${SOC_ALERT_EMAIL}|g" \
    -e "s|smtp\.example\.com:25|${SMTP_SERVER}|g" \
    -e "s|splunk-siem@example\.com|${SMTP_FROM}|g" \
    -e "s|https://soc-portal\.example\.com/api/v1/alerts|${SOC_WEBHOOK_URL}|g" \
    -e "s|https://splunk\.example\.com:8000|https://${INDEXER_HOST}:${SPLUNK_WEB_PORT}|g"

# Local overrides that must never live in default/ (credentials, site email).
cat > "${APP_DST}/local/alert_actions.conf" <<EOF
# Site-local overrides. Generated by 05_deploy_app.sh - edit splunk.env, not
# this file.
[email]
mailserver = ${SMTP_SERVER}
from = ${SMTP_FROM}
hostname = https://${INDEXER_HOST}:${SPLUNK_WEB_PORT}
to = ${SOC_ALERT_EMAIL}

[webhook]
param.url = ${SOC_WEBHOOK_URL}
EOF

chown -R "${SPLUNK_USER}:${SPLUNK_GROUP}" "${APP_DST}"
find "${APP_DST}" -type d -exec chmod 755 {} +
find "${APP_DST}" -type f -exec chmod 644 {} +
[[ -d "${APP_DST}/bin" ]] && find "${APP_DST}/bin" -type f -exec chmod 755 {} + || true
chmod 600 "${APP_DST}/local/alert_actions.conf"

# --- configuration validation before we restart ----------------------------
log "validating configuration with btool"
local_errors=0
for conf in savedsearches macros props transforms eventtypes tags alert_actions indexes; do
    if ! sudo -u "${SPLUNK_USER}" "${SPLUNK_HOME}/bin/splunk" btool "${conf}" list \
            --debug >/dev/null 2>"${TMPDIR:-/tmp}/btool_${conf}.err"; then
        warn "btool reported problems in ${conf}.conf:"
        sed 's/^/        /' "${TMPDIR:-/tmp}/btool_${conf}.err" >&2
        local_errors=$((local_errors + 1))
    fi
done
(( local_errors == 0 )) || warn "${local_errors} conf file(s) had btool warnings - review above"

# --- HEC token for the scripted / API inputs -------------------------------
provision_hec() {
    local token
    token=$(sudo -u "${SPLUNK_USER}" "${SPLUNK_HOME}/bin/splunk" http-event-collector create \
        siem_core_hec -uri "https://127.0.0.1:${SPLUNK_MGMT_PORT}" \
        -index siem_summary -sourcetype siem:api \
        -auth "${SPLUNK_ADMIN_USER}:${SPLUNK_ADMIN_PASSWORD}" 2>/dev/null \
        | awk '/token=/ {print $NF}') || true
    if [[ -n "${token:-}" ]]; then
        log "HEC token provisioned: ${token}"
        sed -i "s|^token = 00000000-0000-0000-0000-000000000000|token = ${token}|" \
            "${SPLUNK_HOME}/etc/system/local/inputs.conf" 2>/dev/null || true
    else
        warn "HEC token not provisioned (may already exist) - check Settings > Data inputs"
    fi
}

# --- restart + verify ------------------------------------------------------
log "restarting Splunk to load the app"
splunk_cmd "${SPLUNK_HOME}" restart
provision_hec

log "saved searches now registered in siem_core:"
sudo -u "${SPLUNK_USER}" "${SPLUNK_HOME}/bin/splunk" search \
    '| rest /servicesNS/-/siem_core/saved/searches | search eai:acl.app=siem_core title!=default | table title, disabled, cron_schedule | sort title' \
    -auth "${SPLUNK_ADMIN_USER}:${SPLUNK_ADMIN_PASSWORD}" 2>/dev/null | sed 's/^/      /' || \
    warn "could not enumerate saved searches - check the app in the UI"

log "app deployed. Open https://${INDEXER_HOST}:${SPLUNK_WEB_PORT}/en-US/app/siem_core/soc_overview"
